/* ============================================================
 * 极简 Hash 路由
 *
 * 原理：网址 # 后面的部分（如 #/checkin）变化时，
 * 浏览器不会刷新页面，只会触发 hashchange 事件。
 * 我们监听这个事件，切换显示的页面组件——这就是"单页应用"。
 *
 * 为什么用 # 而不是普通路径（/checkin）？
 * 因为 GitHub Pages 是纯静态托管，访问 /checkin 它真去找
 * 一个叫 checkin 的文件，找不到就 404；而 # 后面的部分
 * 永远不会发给服务器，刷新也安全。
 * ============================================================ */

/* 当前路由，如 '/'、'/checkin' */
function currentRoute() {
  return location.hash.replace(/^#/, '') || '/';
}

/* 跳转页面 */
function navigate(path) {
  location.hash = '#' + path;
}
